'use client';
import { useEffect, useState } from 'react';
import { Topbar } from '@/components/layout/Topbar';
import api from '@/lib/api';
import Link from 'next/link';

interface Deck {
  id: string;
  title: string;
  description?: string;
  cardCount?: number;
  course?: { id: string; title: string };
}

export default function FlashcardsPage() {
  const [decks, setDecks] = useState<Deck[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    api.get('/flashcards/decks').then(r => setDecks(r.data ?? [])).catch(() => {}).finally(() => setLoading(false));
  }, []);

  return (
    <div className="flex flex-col min-h-screen bg-surface">
      <Topbar title="Flashcards" backHref="/student/dashboard" />
      <div className="flex-1 p-4 max-w-2xl mx-auto w-full">
        {loading ? (
          <div className="flex justify-center py-20">
            <div className="w-8 h-8 border-2 border-azure border-t-transparent rounded-full animate-spin" />
          </div>
        ) : decks.length === 0 ? (
          <div className="text-center py-20">
            <div className="w-16 h-16 bg-cloud rounded-2xl flex items-center justify-center mx-auto mb-4 text-2xl">🃏</div>
            <p className="font-bold text-navy mb-1">No flashcard decks yet</p>
            <p className="text-sm text-muted">Flashcard decks are created by your teachers or generated by AI from lesson content.</p>
          </div>
        ) : (
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {decks.map(deck => (
              <Link key={deck.id} href={`/student/flashcards/${deck.id}`}
                className="bg-white rounded-2xl border border-cloud p-5 hover:border-azure/40 hover:shadow-sm transition group">
                <div className="flex items-start justify-between gap-3 mb-3">
                  <div className="w-10 h-10 bg-azure/10 rounded-xl flex items-center justify-center text-lg flex-shrink-0">🃏</div>
                  <span className="text-xs font-semibold text-azure bg-azure/10 rounded-full px-2.5 py-1">
                    {deck.cardCount ?? '?'} cards
                  </span>
                </div>
                <h3 className="font-bold text-navy mb-1 group-hover:text-azure transition">{deck.title}</h3>
                {deck.description && <p className="text-xs text-muted line-clamp-2">{deck.description}</p>}
                {deck.course && (
                  <p className="text-[10px] text-muted mt-2 font-semibold uppercase tracking-wide">{deck.course.title}</p>
                )}
              </Link>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
